    <h2 class="crit crit--forest">Расстояние Бхаттачарьи</h2>
    <p>
      Фильтровый метод. Считает, насколько статистически разделимы два класса
      в пространстве выбранных признаков - через разницу средних и через
      различие формы распределений.
    </p>
    <p class="prose__note prose__note--forest">
      Метод попарный: он оценивает разделимость конкретной пары классов,
      а не всех сразу, потому что расстояние Бхаттачарьи математически
      определено для двух распределений. По умолчанию берётся пара
      «разреженная застройка» и «леса» как показательный случай.
    </p>

    <h2 class="crit crit--plum">Расстояние Махаланобиса</h2>
    <p>
      Тоже фильтровый метод: расстояние между средними значениями классов,
      но с учётом того, что признаки могут быть скоррелированы. Если признаки
      связаны между собой, равные расстояния образуют не сферы, а вытянутые
      эллипсоиды - обычное евклидово расстояние это игнорирует, а
      Махаланобиса учитывает.
    </p>
    <p>
      В отличие от Бхаттачарьи считается по всем парам классов сразу
      и усредняется, поэтому охватывает весь набор, а не два выбранных класса.
    </p>
    <p class="prose__note prose__note--plum">
      Эти два критерия связаны напрямую: расстояние Махаланобиса -
      это, по сути, первое слагаемое формулы Бхаттачарьи, без второго,
      где стоит логарифм определителя ковариационной матрицы. Информации
      меньше, зато устойчивее: на редких классах, где пикселей мало,
      определитель считается плохо и даёт выбросы.
    </p>

    <h2 class="crit crit--water">Взаимная информация</h2>
    <p>
      Третий фильтровый метод, устроенный принципиально иначе. Бхаттачарья
      и Махаланобис считают средние и ковариации, то есть исходят из того,
      что классы распределены нормально. Взаимная информация ничего такого
      не предполагает: она измеряет, насколько знание признака уменьшает
      неопределённость в классе, при любой форме зависимости.
    </p>
    <p class="prose__note prose__note--water">
      Сама по себе взаимная информация оценивает каждый признак отдельно.
      Если два признака почти дублируют друг друга, оба получат высокую
      оценку и оба попадут в набор - хотя второй ничего не добавит.
      Поэтому на каждом шаге из оценки вычитается похожесть кандидата
      на уже отобранные признаки, измеренная корреляцией. Берётся
      наибольшая похожесть: достаточно совпасть с одним признаком из
      набора, чтобы стать лишним.
    </p>

    <h2 class="crit crit--gold">Отбор через kNN</h2>
    <p>
      Метод-обёртка: на каждом шаге обучает классификатор ближайших соседей
      и смотрит на его точность по кросс-валидации. Учитывает все классы
      одновременно, поскольку точность - естественная многоклассовая метрика.
    </p>
    <p class="prose__note prose__note--gold">
      Расплата - время. Обучение классификатора на каждом шаге для каждого
      признака-кандидата обходится на порядки дороже, чем расчёт расстояния
      по формуле. На практике разница доходит до сотни раз.
    </p>

    <hr class="prose__divider" />

    <h2>Как оценивается результат</h2>
    <p>
      Итоговое качество всех наборов измеряется одинаково: отобранные
      признаки подаются классификатору ближайших соседей, обучение идёт
      на 70% данных, проверка - на отложенных 30%. Одна линейка для всех
      критериев нужна, чтобы наборы можно было сравнивать напрямую.
    </p>
    <p class="prose__note">
      Из этого следует важное: точность, показанная рядом с фильтровым
      критерием, - это не его собственная величина, а результат проверки
      его набора признаков классификатором. Сам критерий выдаёт другое
      число: расстояние D_B или D_M, оно видно на графике отбора.
    </p>

    <h2>Как добавить свои признаки</h2>
    <p>
      Признаки собраны в наборы: спектральные, текстурные и те, что добавил
      сам исследователь. Чтобы добавить свой, не нужно трогать код программы -
      достаточно положить файл в папку <code>user_features</code> рядом
      с папками <code>src</code> и <code>data</code>:
    </p>
    <pre class="code">import numpy as np
from effective_features.feature_sets import register

def compute(ctx):
    gy, gx = np.gradient(ctx.gray)
    return {'Gradient': np.hypot(gx, gy).astype(np.float32)}

register(
    id='gradient',
    name='Модуль градиента',
    description='Резкость переходов яркости',
    compute=compute,
)</pre>
    <p>
      Функция получает контекст и возвращает словарь: имя признака →
      массив той же формы, что и снимок. В контексте есть
      <code>ctx.gray</code> - яркость, <code>ctx.image</code> - все каналы,
      <code>ctx.band('nir')</code> - канал по роли,
      <code>ctx.window_sizes</code> - размеры окон из настроек.
    </p>
    <p class="prose__note">
      Новые признаки добавляются в конец списка, поэтому номера встроенных
      не сдвигаются. Ошибка в пользовательском наборе не роняет расчёт:
      программа сообщает о ней и продолжает работу без этого набора.
    </p>

    <h2>Как добавить свой критерий</h2>
    <p>
      Список критериев собран в одном месте - файле
      <code>criteria.py</code>. Чтобы добавить новый, достаточно написать
      функцию отбора и дописать одну запись в реестр: интерфейс подхватит
      её сам, вместе с названием, цветом и подписью на графике.
    </p>
